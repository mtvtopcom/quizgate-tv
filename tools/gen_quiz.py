OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "app", "src", "main", "assets", "quiz")


def main():
    os.makedirs(OUT, exist_ok=True)
    total = 0
    for grade, items in DATA.items():
        rows = []
        for i, (stem, opts, ans, exp) in enumerate(items, start=1):
            assert len(opts) == 4, (grade, stem)
            assert 0 <= ans < 4, (grade, stem)
            assert len(set(opts)) == 4, ("选项重复", grade, stem)
            rows.append({
                "id": "g%d-%03d" % (grade, i),
                "subject": "综合",
                "stem": stem,
                "options": opts,
                "answerIndex": ans,
                "explanation": exp,
            })
        doc = {"version": 1, "grade": grade, "items": rows}
        path = os.path.join(OUT, "grade_%d.json" % grade)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(doc, f, ensure_ascii=False, indent=1)
            f.write("\n")
        total += len(rows)
        print("grade %d: %d 题 -> %s" % (grade, len(rows), os.path.basename(path)))
    print("total: %d 题" % total)


if __name__ == "__main__":
    main()
